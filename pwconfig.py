"""Pure logic for PipeWrench's own device config: devices.json (buses, labels, hidden rows, clock) and the
two files generated from it, the PipeWire drop-in for buses and the WirePlumber label rules.
No curses and no subprocess calls here; callers pass a runner. Plan: docs/devices-v2-plan.md.
"""
import difflib
import json
import os
import re
import shutil
from pathlib import Path

RATES = [44100, 48000, 88200, 96000, 176400, 192000]  # pwcore force-rate choices, minus "do not force"
QUANTA = [8, 16, 32, 64, 128, 256, 512, 1024, 2048, 4096, 8192]  # pwcore's buffer choices
# Saved clock settings (Settings → Save): devices.json key, drop-in property, live settings key, stock value.
# A key left None is not written, so PipeWire's own default holds. The rate key is the older clock_rate.
CLOCK = [("clock_rate", "default.clock.rate", "clock.force-rate", 0),
         ("clock_quantum", "default.clock.quantum", "clock.force-quantum", 0),
         ("clock_min_quantum", "default.clock.min-quantum", "clock.min-quantum", 32),
         ("clock_max_quantum", "default.clock.max-quantum", "clock.max-quantum", 2048)]
RESTART_PIPEWIRE = ["systemctl", "--user", "restart", "pipewire", "pipewire-pulse", "wireplumber"]
RESTART_WIREPLUMBER = ["systemctl", "--user", "restart", "wireplumber"]
VERSION_CMD = ["wireplumber", "--version"]
MARK = "Generated by PipeWrench"
MARKS = (MARK, "Generated by pwctl")  # files the old name made are still ours
APP_DIR, LEGACY_DIR = "pipewrench", "pwctl"  # the settings folder under ~/.config; renamed 2026-10-24

_BUS = re.compile(r"[A-Za-z0-9_-]{1,32}")


class ConfigError(Exception):
    pass


# --- devices.json --------------------------------------------------------------

def default_config():
    return {"version": 2, "clock_rate": None, "buses": [], "labels": {}, "hidden": [], "boost": []}


def config_path():
    if os.environ.get("PIPEWRENCH_DEVICES"):
        return Path(os.environ["PIPEWRENCH_DEVICES"])
    return app_dir() / "devices.json"


def app_dir():
    return _config_home() / APP_DIR


def migrate_config_dir():
    """Copy ~/.config/pwctl to ~/.config/pipewrench once, keeping the old folder. Returns what it did, or None."""
    new, old = app_dir(), _config_home() / LEGACY_DIR
    if new.exists() or not old.is_dir():
        return None
    shutil.copytree(old, new, ignore=shutil.ignore_patterns("*.tmp"))
    return f"copied your settings from {old} to {new}; the old folder is kept"


def _config_home():
    return Path(os.environ.get("XDG_CONFIG_HOME") or Path.home() / ".config")


def _check_text(text, what):
    if not isinstance(text, str) or not text.strip() or any(c in text for c in '"\\\n\r'):
        raise ValueError(f"{what}: must be non-empty text without quotes, backslashes or newlines")


def validate_config(c):
    if c.get("clock_rate") is not None and c["clock_rate"] not in RATES:
        raise ValueError(f"clock rate {c['clock_rate']!r} is not one of {RATES}")
    for key, *_ in CLOCK[1:]:
        if c.get(key) is not None and c[key] not in QUANTA:
            raise ValueError(f"{key}: buffer {c[key]!r} is not one of {QUANTA}")
    lo, hi = c.get("clock_min_quantum"), c.get("clock_max_quantum")
    if lo is not None and hi is not None and lo > hi:
        raise ValueError(f"min buffer {lo} is larger than max buffer {hi}")
    seen = set()
    for b in c.get("buses", []):
        if not isinstance(b.get("name"), str) or not _BUS.fullmatch(b["name"]):
            raise ValueError(f"bus name {b.get('name')!r} must be 1-32 letters, digits, - or _")
        if b["name"] in seen:
            raise ValueError(f"bus {b['name']}: duplicate name")
        _check_text(b.get("label"), f"bus {b['name']} label")
        seen.add(b["name"])
    labels = c.get("labels", {})
    if not isinstance(labels, dict):
        raise ValueError("labels must be a mapping of node name to label")
    for name, label in labels.items():
        _check_text(name, "label node name")
        _check_text(label, f"label for {name}")
    hidden = c.get("hidden", [])
    if not isinstance(hidden, list) or not all(isinstance(h, str) for h in hidden):
        raise ValueError("hidden must be a list of node or card names")
    boost = c.get("boost", [])
    if not isinstance(boost, list) or not all(isinstance(b, str) for b in boost):
        raise ValueError("boost must be a list of node names")


def migrate(c):
    """v1 (GCS-8 loopback pairs) → v2. The pairs went to the gcs-8-linux UCM profile."""
    out = {"version": 2, "clock_rate": c.get("clock_rate"), "buses": c.get("buses", []),
           "labels": c.get("labels", {}), "hidden": c.get("hidden", []), "boost": c.get("boost", [])}
    out.update({key: c[key] for key, *_ in CLOCK[1:] if key in c})  # saved buffers; absent until first saved
    return out


def load_config(path):
    path = Path(path)
    if not path.exists():
        return default_config()
    c = migrate(json.loads(path.read_text()))
    validate_config(c)
    return c


def save_config(path, c):
    validate_config(c)
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(json.dumps(c, indent=2) + "\n")
    os.replace(tmp, path)


# --- edits: each returns a new, validated config ---------------------------------

def clock_fields(live):
    """devices.json clock keys from the live settings: an unforced (0) or stock value saves as None."""
    out = {}
    for key, _, live_key, stock in CLOCK:
        v = live.get(live_key)
        out[key] = v if isinstance(v, int) and v and v != stock else None
    return out


def has_clock(c):
    return any(c.get(key) for key, *_ in CLOCK)


def _copy(c):
    return json.loads(json.dumps(c))


def set_label(c, name, label):
    """Label a node; a bus name relabels the bus. Empty or None clears a node label."""
    c = _copy(c)
    bus = next((b for b in c["buses"] if b["name"] == name), None)
    if bus:
        bus["label"] = label
    elif label is None or not label.strip():
        c["labels"].pop(name, None)
    else:
        c["labels"][name] = label
    validate_config(c)
    return c


def add_bus(c, name, label=None):
    c = _copy(c)
    c["buses"].append({"name": name, "label": label or name})
    validate_config(c)
    return c


def delete_bus(c, name):
    c = _copy(c)
    bus = next((b for b in c["buses"] if b["name"] == name), None)
    if not bus:
        raise KeyError(name)
    c["buses"].remove(bus)
    return c


def set_boost(c, name, on):
    """A node allowed past 100% without asking (the Mixer's Don't ask again), or locked again."""
    c = _copy(c)
    c["boost"] = [b for b in c.get("boost", []) if b != name] + ([name] if on else [])
    return c


def toggle_hidden(c, name):
    c = _copy(c)
    c["hidden"] = [h for h in c["hidden"] if h != name] if name in c["hidden"] else c["hidden"] + [name]
    return c


# --- PipeWire drop-in: buses and clock --------------------------------------------

def dropin_path():
    return _config_home() / "pipewire" / "pipewire.conf.d" / "50-pipewrench-devices.conf"


def _block(lines, indent):
    return "".join(" " * indent + line + "\n" for line in lines)


def render_bus(b):
    args = ["factory.name = support.null-audio-sink",
            f'node.name = "{b["name"]}"',
            f'node.description = "{b["label"]}"',
            'media.class = "Audio/Duplex"',
            "audio.position = [ FL FR ]",
            "object.linger = true",
            "monitor.channel-volumes = true"]
    return "    {   factory = adapter\n        args = {\n" + _block(args, 12) + "        }\n    }\n"


def render_dropin(c):
    validate_config(c)
    parts = [f"# {MARK} from devices.json. Do not edit by hand:\n"
             "# change buses with `pwrench devices`, then apply.\n"]
    props = [f"    {prop} = {c[key]}\n" for key, prop, _, _ in CLOCK if c.get(key)]
    if props:
        parts.append("context.properties = {\n" + "".join(props) + "}\n")
    if c.get("buses"):
        parts.append("context.objects = [\n" + "".join(render_bus(b) for b in c["buses"]) + "]\n")
    return "\n".join(parts)


# --- WirePlumber label rules -----------------------------------------------------

def wireplumber_version(run):
    rc, out = run(VERSION_CMD)
    m = re.search(r"libwireplumber (\d+)\.(\d+)\.(\d+)", out or "")
    if rc != 0 or not m:
        raise ConfigError(f"could not read the WirePlumber version: {(out or '').strip() or f'exit {rc}'}")
    return tuple(int(x) for x in m.groups())


def labels_path(version):
    base = _config_home() / "wireplumber"
    if version < (0, 5, 0):
        return base / "main.lua.d" / "51-pipewrench-labels.lua"
    return base / "wireplumber.conf.d" / "51-pipewrench-labels.conf"


def _monitor(name):
    return "bluez" if name.startswith("bluez_") else "alsa"


def render_labels(c, version):
    validate_config(c)
    lua = version < (0, 5, 0)
    comment = "--" if lua else "#"
    out = (f"{comment} {MARK} from devices.json. Do not edit by hand:\n"
           f"{comment} change labels with `pwrench devices label`, then apply.\n")
    labels = sorted(c.get("labels", {}).items())
    for monitor in ("alsa", "bluez"):
        rules = [(n, label) for n, label in labels if _monitor(n) == monitor]
        if not rules:
            continue
        if lua:
            for name, label in rules:
                out += (f"\ntable.insert({monitor}_monitor.rules, {{\n"
                        f'  matches = {{ {{ {{ "node.name", "equals", "{name}" }} }} }},\n'
                        f'  apply_properties = {{ ["node.description"] = "{label}" }},\n'
                        "})\n")
        else:
            out += f"\nmonitor.{monitor}.rules = [\n"
            for name, label in rules:
                out += ("  {\n"
                        f'    matches = [ {{ node.name = "{name}" }} ]\n'
                        f'    actions = {{ update-props = {{ node.description = "{label}" }} }}\n'
                        "  }\n")
            out += "]\n"
    return out


# --- generated-file safety: shared by the drop-in and the label rules -------------

def _backup(path):
    return path.with_name(path.name + ".bak")


def legacy_path(path):
    """Where the generated file lived before the rename (50-pipewrench-devices.conf, 51-pipewrench-labels.*)."""
    path = Path(path)
    return path.with_name(path.name.replace("-pipewrench-", "-pwctl-"))


def live_path(path):
    """The file PipeWire or WirePlumber reads now: the old name until the first apply after the rename."""
    path, old = Path(path), legacy_path(path)
    return old if old.exists() and not path.exists() and not _backup(path).exists() else path


def check_ours(path):
    path = Path(path)
    if path.exists() and not any(m in path.read_text().split("\n", 1)[0] for m in MARKS):
        raise ConfigError(f"{path} was not generated by PipeWrench; move it aside first")


def _retire_legacy(path):
    """Before the first write under the new name: the old file becomes its .bak and goes. The old .bak stays
    (PipeWire reads only *.conf and WirePlumber only *.lua/*.conf, so it's inert) as the older history."""
    old = legacy_path(path)
    if old == path or not old.exists() or path.exists():
        return
    check_ours(old)
    path.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(old, _backup(path))
    old.unlink()


def diff_generated(path, text):
    path = Path(path)
    old = path.read_text() if path.exists() else ""
    return "".join(difflib.unified_diff(old.splitlines(True), text.splitlines(True),
                                        f"{path} (current)", f"{path} (new)"))


def write_generated(path, text):
    """Atomic write, keeping the previous file as .bak. Returns False when nothing changed."""
    path = Path(path)
    check_ours(path)
    check_ours(legacy_path(path))
    _retire_legacy(path)
    if path.exists() and path.read_text() == text:
        return False
    if not path.exists() and _backup(path).exists() and _backup(path).read_text() == text:
        shutil.copy2(_backup(path), path)  # renamed with nothing else to change
        return True
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        shutil.copy2(path, _backup(path))
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(text)
    os.replace(tmp, path)
    return True


def rollback_generated(path):
    path = Path(path)
    check_ours(path)
    if _backup(path).exists():
        os.replace(_backup(path), path)
        return f"restored the previous {path.name}"
    if path.exists():
        path.unlink()
        return f"removed {path.name}"
    return f"nothing to roll back for {path.name}"


def bus_conflicts(c, live_names, applied_text):
    """Buses in the config that already exist live but aren't PipeWrench's yet (e.g. made by a script).
    Applying would create a second node with the same name."""
    return [b["name"] for b in c.get("buses", [])
            if b["name"] in live_names and f'node.name = "{b["name"]}"' not in (applied_text or "")]


def check_applied(c, live):
    """Problems after an apply: missing buses, labels not showing. live maps node name -> label."""
    problems = [f"{b['name']}: bus missing" for b in c.get("buses", []) if b["name"] not in live]
    problems += [f"{name}: shows {live[name]!r}, expected {label!r}"
                 for name, label in sorted(c.get("labels", {}).items()) if name in live and live[name] != label]
    return problems
